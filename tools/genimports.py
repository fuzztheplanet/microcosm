#!/usr/bin/env python3
"""genimports.py - hash the payload's import list for src/mc_start.c.

The MC_IMPORTS(X) list in include/microcosm/mc_imports.h names every library
function the shipped payload calls. The payload carries no symbol names, only
the GNU (dl_new_hash) hash of each entry in list order, cut to its low
MC_IMPORT_HASH_BITS bits (set in the same header).

    python3 tools/genimports.py include/microcosm/mc_imports.h -o build/hello-world/mc_imports_gen.h

This writes MC_IMPORT_HASH_BYTES and "#define MC_IMPORT_HASHES 0x.., ...". Each
hash is stored little-endian in as few whole bytes as the width needs, with no
padding between entries. The script fails if two names in the list collide at
that width. tools/importcheck.py catches collisions with other names the
libraries export, after the link. The output depends only on the header.
"""
import argparse
import os
import re
import sys


def gnu_hash(name: str) -> int:
    h = 5381
    for c in name.encode():
        h = (h * 33 + c) & 0xFFFFFFFF
    return h


def import_names(text: str) -> list:
    m = re.search(r"#define\s+MC_IMPORTS\(X\)((?:[^\n]*\\\n)*[^\n]*)", text)
    if not m:
        raise SystemExit("genimports: no MC_IMPORTS(X) list found")
    return re.findall(r"\bX\((\w+)\)", m.group(1))


def hash_bits(text: str) -> int:
    m = re.search(r"#define\s+MC_IMPORT_HASH_BITS\s+(\d+)", text)
    if not m or not 8 <= int(m.group(1)) <= 32:
        raise SystemExit("genimports: MC_IMPORT_HASH_BITS (8 to 32) not found")
    return int(m.group(1))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("header")
    ap.add_argument("-o", "--output", required=True)
    a = ap.parse_args()
    with open(a.header) as f:
        text = f.read()
    names, bits = import_names(text), hash_bits(text)
    hashes = [gnu_hash(n) & ((1 << bits) - 1) for n in names]
    if len(set(names)) != len(names) or len(set(hashes)) != len(hashes):
        sys.exit("genimports: duplicate name or %d-bit hash in the import list" % bits)
    size = (bits + 7) // 8
    lines = ["/* Generated by tools/genimports.py from %s; do not edit. */" % os.path.basename(a.header),
             "#define MC_IMPORT_HASH_BYTES %d" % size,
             "#define MC_IMPORT_HASHES \\"]
    lines += ["    %s, /* %s */ \\" % (", ".join("0x%02x" % (h >> 8 * i & 255) for i in range(size)), n)
              for h, n in zip(hashes, names)]
    lines += ["", ""]
    text = "\n".join(lines)
    tmp = a.output + ".tmp"
    with open(tmp, "w") as f:
        f.write(text)
    os.replace(tmp, a.output)


if __name__ == "__main__":
    main()
