/*
 * mc_start.c - the packed payload's own entry point and import resolver.
 *
 * Only the payload links this file. It's built with -nostartfiles, so there's
 * no crt1/crti/crtbegin, and with them no __libc_start_main import, init/fini
 * stubs, unwind tables or ELF notes. Before the dynamic loader jumps here, it
 * has already mapped the DT_NEEDED libraries and run their initializers
 * (libc's sets up environ, stdio, TLS and threads). All that's left is what
 * crt1 and __libc_start_main would do for us: find our imports, run main,
 * exit.
 *
 * Imports are found by hash (see mc_imports.h). The loader's r_debug, which our
 * DT_DEBUG points to, lists every mapped object, and we scan each one's dynamic
 * symbol table once. A defined function or object fills a slot when its default
 * (non-hidden) version's name hashes to the wanted value in its low
 * MC_IMPORT_HASH_BITS. GNU indirect functions are resolved by calling them, as
 * the loader would.
 *
 * memcpy and friends live here because the compiler may emit calls to them for
 * struct copies and clears, and the payload mustn't import those either. This
 * file is built without LTO so the definitions survive until code generation
 * needs them.
 */
#include <elf.h>
#include <link.h>
#include <stdlib.h>
int main(void);
#include "microcosm/mc_imports.h"
#include "mc_imports_gen.h"   /* MC_IMPORT_HASHES and _BYTES, generated by tools/genimports.py */

struct mc_imports mc_imp;
#define MC_IMPORT_COUNT (sizeof(struct mc_imports) / sizeof(void *))
/* The imports' hashes, back to back: the low MC_IMPORT_HASH_BITS of each,
 * little-endian in MC_IMPORT_HASH_BYTES bytes. resolve() reads 4 bytes at each
 * one and masks them. The array is sized so that the bytes the last read runs
 * past are zero-filled. */
static const unsigned char mc_imp_hash[MC_IMPORT_COUNT * MC_IMPORT_HASH_BYTES + 4 - MC_IMPORT_HASH_BYTES] = {
    MC_IMPORT_HASHES
};
_Static_assert(sizeof(unsigned char[]){ MC_IMPORT_HASHES } == MC_IMPORT_COUNT * MC_IMPORT_HASH_BYTES,
               "import list and hashes differ");
#define MC_IMPORT_HASH_MASK (0xffffffffu >> (32 - MC_IMPORT_HASH_BITS))
typedef unsigned mc_unaligned_u32 __attribute__((aligned(1), may_alias));

static void resolve(void) {
    struct r_debug *dbg = 0;
    for (ElfW(Dyn) *d = _DYNAMIC; d->d_tag != DT_NULL; ++d)
        if (d->d_tag == DT_DEBUG) dbg = (struct r_debug *)d->d_un.d_ptr;
    void **slot = (void **)&mc_imp;
    for (struct link_map *l = dbg->r_map; l; l = l->l_next) {
        const ElfW(Sym) *sym = 0;
        const char *str = 0;
        const ElfW(Half) *ver = 0;
        const Elf32_Word *sysv = 0, *gnu = 0;
        for (ElfW(Dyn) *d = l->l_ld; d->d_tag != DT_NULL; ++d) {
            ElfW(Addr) p = d->d_un.d_ptr;
            if (d->d_tag == DT_SYMTAB) sym = (const ElfW(Sym) *)p;
            if (d->d_tag == DT_STRTAB) str = (const char *)p;
            if (d->d_tag == DT_VERSYM) ver = (const ElfW(Half) *)p;
            if (d->d_tag == DT_HASH) sysv = (const Elf32_Word *)p;
            if (d->d_tag == DT_GNU_HASH) gnu = (const Elf32_Word *)p;
        }
        /* The loader relocates every object's dynamic section in place, except
         * for the read-only vDSO. The vDSO's clock_gettime would shadow libc's
         * (and it returns -errno), so skip any object whose table hasn't been
         * relocated. */
        if (!sym || (ElfW(Addr))str < l->l_addr) continue;
        /* the symbol count: nchain from a SysV hash table, or else the end of
         * the GNU table's last chain */
        Elf32_Word n = 0;
        if (sysv) n = sysv[1];
        else if (gnu) {
            const Elf32_Word *bucket = gnu + 4 + gnu[2] * (sizeof(ElfW(Addr)) / 4);
            const Elf32_Word *chain = bucket + gnu[0] - gnu[1];
            for (Elf32_Word b = 0; b < gnu[0]; ++b) if (bucket[b] > n) n = bucket[b];
            if (n) while (!(chain[n] & 1)) ++n;
            ++n;
        }
        for (Elf32_Word i = 0; i < n; ++i) {
            const ElfW(Sym) *s = &sym[i];
            unsigned type = ELF64_ST_TYPE(s->st_info);
            if (s->st_shndx == SHN_UNDEF || (ver && (ver[i] & 0x8000)) ||
                (type != STT_FUNC && type != STT_GNU_IFUNC && type != STT_OBJECT)) continue;
            unsigned h = 5381;                          /* the GNU (dl_new_hash) name hash */
            for (const unsigned char *c = (const unsigned char *)str + s->st_name; *c; ++c) h = h * 33 + *c;
            h &= MC_IMPORT_HASH_MASK;
            for (unsigned k = 0; k < MC_IMPORT_COUNT; ++k)
                if (!slot[k] && (*(const mc_unaligned_u32 *)(mc_imp_hash + k * MC_IMPORT_HASH_BYTES)
                                 & MC_IMPORT_HASH_MASK) == h) {
                    void *a = (void *)(l->l_addr + s->st_value);
                    slot[k] = type == STT_GNU_IFUNC ? ((void *(*)(void))a)() : a;
                }
        }
    }
}

/* This does the job of crt1 + __libc_start_main, plus crtfastmath, which
 * -ffast-math links but -nostartfiles drops. Denormals flush to zero (MXCSR
 * FTZ|DAZ), and the audio thread inherits that. The loader's finalizer (in
 * rdx) isn't registered. The payload leaves at once through exit_group
 * (mc_exit) without running any library's exit handlers. That way nothing
 * tears the GL driver or the audio library down under the audio thread, which
 * may still be in the middle of a write. The kernel releases the window, the
 * context and the sound device as it would for any process. */
__attribute__((noreturn)) void mc_exit(int code) {
    __asm__ volatile("syscall" : : "a"(231), "D"(code));
    __builtin_unreachable();
}
__attribute__((used, noreturn)) static void mc_start(void) {
    unsigned csr;
    __asm__ volatile("stmxcsr %0" : "=m"(csr));
    csr |= 0x8040;
    __asm__ volatile("ldmxcsr %0" : : "m"(csr));
    resolve();
    mc_exit(main());
}
__asm__(".text\n.globl _start\n.type _start,@function\n_start:\n"
        "  xor %ebp, %ebp\n  and $-16, %rsp\n  call mc_start\n");

/* Local copies of the libcalls the compiler emits. rep movsb/stosb is small,
 * fast on anything with ERMS, and can't be turned back into a call to itself.
 * __powisf2 is needed because fast-math folds t*t*t into powi. This is
 * libgcc's algorithm, copied here to keep libgcc's version and its unwind
 * table out of the payload. */
__attribute__((used)) float __powisf2(float x, int m) {
    unsigned n = m < 0 ? -(unsigned)m : (unsigned)m;
    float y = n % 2 ? x : 1;
    while (n >>= 1) {
        x = x * x;
        if (n % 2) y = y * x;
    }
    return m < 0 ? 1 / y : y;
}
__attribute__((used)) void *memcpy(void *d, const void *s, size_t n) {
    void *r = d;
    __asm__ volatile("rep movsb" : "+D"(d), "+S"(s), "+c"(n) : : "memory");
    return r;
}
__attribute__((used)) void *memmove(void *d, const void *s, size_t n) {
    void *r = d;
    if ((const char *)d <= (const char *)s || (const char *)d >= (const char *)s + n)
        __asm__ volatile("rep movsb" : "+D"(d), "+S"(s), "+c"(n) : : "memory");
    else {
        d = (char *)d + n - 1; s = (const char *)s + n - 1;
        __asm__ volatile("std\n rep movsb\n cld" : "+D"(d), "+S"(s), "+c"(n) : : "memory");
    }
    return r;
}
__attribute__((used)) void *memset(void *d, int c, size_t n) {
    void *r = d;
    __asm__ volatile("rep stosb" : "+D"(d), "+c"(n) : "a"(c) : "memory");
    return r;
}
__attribute__((used)) int memcmp(const void *a, const void *b, size_t n) {
    const unsigned char *x = a, *y = b;
    for (; n; --n, ++x, ++y) if (*x != *y) return *x - *y;
    return 0;
}
